def load_manifest():
    if not MANIFEST_FILE.exists():
        return []
    try:
        return json.loads(MANIFEST_FILE.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, TypeError):
        return []


def write_if_changed(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    print(f"generated {path.relative_to(ROOT)}")
    return True


def main():
    articles = load_articles()
    changed = False

    changed |= write_if_changed(DATA_FILE, build_registry(articles))

    for article in articles:
        selector_path = SELECTOR_DIR / f"{article['slug']}.js"
        changed |= write_if_changed(selector_path, selector_script(article["slug"]))

    previously_managed = set(load_manifest())
    managed = set(previously_managed)
    current_slugs = {article["slug"] for article in articles}

    for article in articles:
        target = ROOT / route_for(article) / article["slug"] / "index.html"
        if article["slug"] in previously_managed or not target.exists():
            changed |= write_if_changed(target, static_page(article))
            managed.add(article["slug"])

    for stale_slug in sorted(previously_managed - current_slugs):
        for route in ROUTE_BY_CATEGORY.values():
            stale_page = ROOT / route / stale_slug / "index.html"
            if stale_page.exists():
                stale_page.unlink()
                try:
                    stale_page.parent.rmdir()
                except OSError:
                    pass
                print(f"removed {stale_page.relative_to(ROOT)}")
                changed = True
        stale_selector = SELECTOR_DIR / f"{stale_slug}.js"
        if stale_selector.exists():
            stale_selector.unlink()
            print(f"removed {stale_selector.relative_to(ROOT)}")
            changed = True
        managed.discard(stale_slug)

    manifest = json.dumps(sorted(managed), ensure_ascii=False, indent=2) + "\n"
    changed |= write_if_changed(MANIFEST_FILE, manifest)

    if not changed:
        print("article build already up to date")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"article build failed: {exc}", file=sys.stderr)
        raise
