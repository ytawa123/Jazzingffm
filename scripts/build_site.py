#!/usr/bin/env python3
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT_DIR = ROOT / "content" / "articles"
DATA_FILE = ROOT / "data" / "articles.js"
SELECTOR_DIR = ROOT / "articles"
MANIFEST_FILE = ROOT / "data" / "generated-article-pages.json"

ROUTE_BY_CATEGORY = {
    "interviews": "interviews",
    "highlights": "features",
}

REQUIRED_I18N = ("title", "cardTitle", "cardSubtitle", "caption", "excerpt", "imageLabel", "body", "bio")


def load_articles():
    files = sorted(CONTENT_DIR.glob("*.json"))
    if not files:
        raise SystemExit("No article JSON files found in content/articles.")

    articles = []
    slugs = set()
    for path in files:
        with path.open("r", encoding="utf-8") as handle:
            article = json.load(handle)
        validate_article(article, path)
        if article["slug"] in slugs:
            raise SystemExit(f"Duplicate article slug: {article['slug']}")
        slugs.add(article["slug"])
        article["_source"] = str(path.relative_to(ROOT))
        articles.append(article)

    articles.sort(key=lambda item: item["date"]["iso"], reverse=True)
    return articles


def validate_article(article, path):
    required = ["slug", "version", "category", "categoryLabel", "date", "images", "seo", *REQUIRED_I18N]
    missing = [key for key in required if key not in article]
    if missing:
        raise SystemExit(f"{path}: missing fields: {', '.join(missing)}")

    if article["category"] not in ROUTE_BY_CATEGORY:
        raise SystemExit(f"{path}: unsupported category {article['category']!r}")

    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", article["slug"]):
        raise SystemExit(f"{path}: slug must be lowercase kebab-case")

    for key in (*REQUIRED_I18N, "categoryLabel"):
        value = article[key]
        if not isinstance(value, dict) or not value.get("en") or not value.get("de"):
            raise SystemExit(f"{path}: {key} must contain non-empty en/de values")

    date = article["date"]
    if not all(date.get(key) for key in ("iso", "en", "de")):
        raise SystemExit(f"{path}: date must contain iso/en/de")

    if not isinstance(article["images"], list):
        raise SystemExit(f"{path}: images must be a list")

    for image_path in article["images"]:
        image = ROOT / image_path
        if not image.exists():
            raise SystemExit(f"{path}: image does not exist: {image_path}")

    seo = article["seo"]
    if not seo.get("description") or not seo.get("headline"):
        raise SystemExit(f"{path}: seo.description and seo.headline are required")


def runtime_article(article):
    return {
        "slug": article["slug"],
        "category": article["category"],
        "categoryLabel": article["categoryLabel"],
        "title": article["title"],
        "cardTitle": article["cardTitle"],
        "cardSubtitle": article["cardSubtitle"],
        "date": {"en": article["date"]["en"], "de": article["date"]["de"]},
        "images": article["images"],
        "caption": article["caption"],
        "excerpt": article["excerpt"],
        "imageLabel": article["imageLabel"],
        "body": article["body"],
    }


def build_registry(articles):
    runtime = [runtime_article(article) for article in articles]
    bios = {article["slug"]: article["bio"] for article in articles}
    return (
        "// GENERATED from /content/articles by scripts/build_site.py.\n"
        "// Do not edit this file directly.\n"
        "window.JAZZING_ARTICLES = "
        + json.dumps(runtime, ensure_ascii=False, indent=2)
        + ";\n\nwindow.JAZZING_ARTICLE_BIOS = "
        + json.dumps(bios, ensure_ascii=False, indent=2)
        + ";\n"
    )


def selector_script(slug):
    return f'''// GENERATED compatibility selector for direct static article pages.
(function() {{
  const slug = {json.dumps(slug)};
  const articles = window.JAZZING_ARTICLES || [];
  const index = articles.findIndex(function(article) {{
    return article.slug === slug;
  }});

  if (index > 0 && window.location.pathname !== "/" && window.location.pathname !== "/index.html") {{
    const article = articles.splice(index, 1)[0];
    articles.unshift(article);
  }}
}})();
'''


def page_type(article):
    return "Interview" if article["category"] == "interviews" else "Feature"


def route_for(article):
    return ROUTE_BY_CATEGORY[article["category"]]


def canonical_for(article):
    return f"https://jazzingffm.de/{route_for(article)}/{article['slug']}/"


def first_image(article):
    return article["images"][0] if article["images"] else ""


def bold_static_speaker(body, musician_name):
    return body.replace(
        f"<p>{musician_name}:",
        f"<p><strong>{html.escape(musician_name)}</strong>:",
    )


